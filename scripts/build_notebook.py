def build() -> Path:
    notebook = nbf.v4.new_notebook()
    notebook["cells"] = [
        nbf.v4.new_markdown_cell(source) if kind == "markdown"
        else nbf.v4.new_code_cell(source)
        for kind, source in CELLS
    ]
    notebook["metadata"] = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python", "version": "3.12"},
    }
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    nbf.write(notebook, NOTEBOOK)
    return NOTEBOOK


if __name__ == "__main__":
    path = build()
    print(f"[notebook] wrote {path}")
    result = subprocess.run(
        [sys.executable, "-m", "nbconvert", "--to", "notebook", "--execute",
         "--inplace", "--ExecutePreprocessor.timeout=900", str(path)],
        cwd=ROOT, check=False,
    )
    print(f"[notebook] execution exit code: {result.returncode}")
    raise SystemExit(result.returncode)
